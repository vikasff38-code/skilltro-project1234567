-- H2 schema for the local SkillTro database. Flyway is the sole schema manager.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL
);

CREATE TABLE worker_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  occupation VARCHAR(255),
  experience_years INTEGER NOT NULL DEFAULT 0,
  location VARCHAR(255),
  work_description VARCHAR(4000),
  demo BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE employer_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  organization VARCHAR(255),
  location VARCHAR(255),
  description VARCHAR(2000),
  demo BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  name VARCHAR(255) NOT NULL UNIQUE,
  category VARCHAR(255)
);

CREATE TABLE worker_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  worker_profile_id BIGINT NOT NULL REFERENCES worker_profiles(id),
  skill_id BIGINT NOT NULL REFERENCES skills(id),
  state VARCHAR(255) NOT NULL,
  evidence VARCHAR(2000),
  CONSTRAINT uk_worker_skill UNIQUE (worker_profile_id, skill_id)
);

CREATE TABLE assessment_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  skill_id BIGINT NOT NULL REFERENCES skills(id),
  prompt VARCHAR(1000) NOT NULL,
  option_a VARCHAR(255) NOT NULL,
  option_b VARCHAR(255) NOT NULL,
  option_c VARCHAR(255) NOT NULL,
  option_d VARCHAR(255) NOT NULL,
  correct_option INTEGER NOT NULL
);

CREATE TABLE assessment_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  worker_profile_id BIGINT NOT NULL REFERENCES worker_profiles(id),
  skill_id BIGINT NOT NULL REFERENCES skills(id),
  score INTEGER NOT NULL,
  total INTEGER NOT NULL,
  answers_json TEXT NOT NULL,
  demo BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  employer_id BIGINT NOT NULL REFERENCES employer_profiles(id),
  title VARCHAR(255) NOT NULL,
  location VARCHAR(255) NOT NULL,
  description VARCHAR(4000),
  demo BOOLEAN NOT NULL DEFAULT TRUE,
  open BOOLEAN NOT NULL DEFAULT TRUE,
  safety_requirements VARCHAR(1000),
  minimum_experience_years INTEGER NOT NULL DEFAULT 0,
  pay_min INTEGER,
  pay_max INTEGER,
  pay_period VARCHAR(32) NOT NULL DEFAULT 'PROJECT'
);

CREATE TABLE job_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  job_id BIGINT NOT NULL REFERENCES jobs(id),
  skill_id BIGINT NOT NULL REFERENCES skills(id),
  requirement_type VARCHAR(255) NOT NULL,
  CONSTRAINT uk_job_skill_requirement UNIQUE (job_id, skill_id, requirement_type)
);

CREATE TABLE applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  job_id BIGINT NOT NULL REFERENCES jobs(id),
  worker_profile_id BIGINT NOT NULL REFERENCES worker_profiles(id),
  status VARCHAR(255) NOT NULL,
  CONSTRAINT uk_application_job_worker UNIQUE (job_id, worker_profile_id)
);

CREATE TABLE matching_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  worker_profile_id BIGINT NOT NULL REFERENCES worker_profiles(id),
  job_id BIGINT NOT NULL REFERENCES jobs(id),
  match_percentage INTEGER NOT NULL,
  matched_required_count INTEGER NOT NULL,
  total_required_count INTEGER NOT NULL,
  matched_skills_json TEXT NOT NULL,
  missing_skills_json TEXT NOT NULL,
  preferred_skills_json TEXT NOT NULL,
  experience_requirement_met BOOLEAN NOT NULL DEFAULT FALSE,
  location_matched BOOLEAN NOT NULL DEFAULT FALSE,
  explanation VARCHAR(1000),
  relevant_evidence_json TEXT NOT NULL DEFAULT '{}',
  CONSTRAINT uk_match_worker_job UNIQUE (worker_profile_id, job_id)
);

CREATE INDEX ix_worker_skills_skill ON worker_skills(skill_id);
CREATE INDEX ix_assessment_questions_skill ON assessment_questions(skill_id);
CREATE INDEX ix_assessment_attempts_worker_created ON assessment_attempts(worker_profile_id, created_at);
CREATE INDEX ix_jobs_open_created ON jobs(open, created_at);
CREATE INDEX ix_job_skills_skill ON job_skills(skill_id);
CREATE INDEX ix_applications_worker_created ON applications(worker_profile_id, created_at);
CREATE INDEX ix_matching_results_job ON matching_results(job_id);
